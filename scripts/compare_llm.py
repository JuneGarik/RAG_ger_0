"""Сравнение моделей Ollama на задачах БЗПО: одинаковые промпты, temperature 0."""

import sys

import httpx

MODELS = sys.argv[1:] or [
    "hf.co/ai-sage/GigaChat3.1-10B-A1.8B-GGUF:Q4_K_M",
    "qwen3.5:9b",
]

CONTEXT = """[1] Проект «СЭД для АО Регионэнерго», 2024. Внедрение СЭД на базе собственной платформы
для 1200 пользователей в 14 филиалах. Срок — 7 месяцев. Миграция 2,3 млн документов из
Lotus Notes. Интеграция с 1С:ERP и порталом госуслуг через СМЭВ.
[2] Проект «Электронный архив Минтранса области», 2023. Оцифровка 400 тыс. листов,
распознавание реквизитов, хранение с ЭП по 63-ФЗ. Команда 9 человек.
[3] Отчёт по проекту Регионэнерго, слайд 12: риски — сопротивление пользователей в филиалах;
мера — 40 обучающих сессий и сеть ключевых пользователей (по 2 в каждом филиале)."""

TASKS = {
    "раздел_заявки": (
        "Ты пишешь раздел тендерной заявки «Опыт и подход к внедрению СЭД» на русском языке, "
        "деловым стилем, 150–220 слов. Используй ТОЛЬКО факты из контекста, после каждого "
        "факта ставь маркер источника [n]. Ничего не выдумывай: если факта нет в контексте, "
        "не пиши его.\n\nКонтекст:\n" + CONTEXT
    ),
    "классификация_json": (
        "Классифицируй запрос пользователя. Верни только JSON без пояснений по схеме "
        '{"task_type": "section_draft" | "fact_lookup" | "list_projects", '
        '"industry": string | null, "years": [int] | null, "confidence": number}.\n\n'
        "Запрос: «Покажи все наши проекты по документообороту в энергетике за 2022–2024 годы»"
    ),
    "шапка_чанка": (
        "Напиши одно предложение (до 30 слов) — контекстную шапку для фрагмента, чтобы он был "
        "понятен в поиске без остального документа. Только предложение.\n\n"
        "Документ: отчёт по проекту «СЭД для АО Регионэнерго», 2024, энергетика.\n"
        "Раздел: Итоги / Сроки и ресурсы.\nФрагмент: «Сроки: 7 мес. Команда: 12 чел. "
        "Пилот — 2 филиала, тиражирование — 12.»"
    ),
}


def run(model: str, prompt: str) -> tuple[str, float, float]:
    body = {
        "model": model,
        "prompt": prompt,
        "stream": False,
        "think": False,
        "keep_alive": 0,
        "options": {"num_ctx": 16384, "temperature": 0},
    }
    if "classification" in prompt or "JSON" in prompt:
        body["format"] = "json"
    d = httpx.post("http://127.0.0.1:11434/api/generate", json=body, timeout=600).json()
    if "error" in d:
        return f"ОШИБКА: {d['error']}", 0.0, 0.0
    tps = d["eval_count"] / d["eval_duration"] * 1e9
    return d["response"].strip(), tps, d["total_duration"] / 1e9


for task, prompt in TASKS.items():
    print(f"\n{'#' * 100}\n# {task}\n{'#' * 100}")
    for model in MODELS:
        text, tps, total = run(model, prompt)
        print(f"\n--- {model}  ({tps:.0f} ток/с, всего {total:.1f} с)\n{text}")
