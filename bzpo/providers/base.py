"""Контракты модуля изоляции (SPEC 6.4).

Единственное место, через которое система обращается к эмбеддингам и
реранкингу. Две реализации — внешний сервис (`external.py`) и локальный
хостинг (`local.py`), переключение конфигурацией через `factory.py`.

Протоколы намеренно узкие: `embed(texts)` и `rerank(query, docs)`. Всё, что
шире (батчи, ретраи, усечение, кэш), — забота реализации, а не вызывающего
кода; иначе логика повторов расползётся по конвейеру индексации и поиску.
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable


class ExternalServiceError(RuntimeError):
    """Базовая ошибка обращения к внешнему сервису.

    Потребитель отличает её от прочих исключений, чтобы показать пользователю
    фиксированное сообщение «сервис поиска временно недоступен» (SPEC 10а,
    таксономия ошибок), а не стектрейс.
    """


class ExternalServiceUnavailable(ExternalServiceError):
    """Повторы исчерпаны: сервис не ответил или отвечает 5xx/429.

    Поднимается только после последней попытки. Запрос пользователя при этом
    отклоняется целиком: частичный ответ без части граней не выдаётся
    (SPEC 6.3) — для текста тендерной заявки немаркированная неполнота
    опаснее отказа.
    """


class ExternalProtocolError(ExternalServiceError):
    """Ответ получен, но он не разбирается: битый JSON или неожиданная схема.

    Не повторяется: 200 с телом не по контракту — это смена версии сервиса или
    чужой эндпоинт, повтор даст то же самое. Требование SPEC 6.4: «битый JSON и
    неожиданная схема — внятное исключение, не молчаливый мусор».
    """


